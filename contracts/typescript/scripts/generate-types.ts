// Generates src/generated/envelope-types.ts from the CEP schemas, so the TypeScript
// types cannot drift from the contract. `--check` fails if the committed file is stale.
import { compile } from "json-schema-to-typescript";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemas = resolve(here, "../../../schemas");
const out = resolve(here, "../src/generated/envelope-types.ts");
const PROFILES = [
  "semantic_snapshot",
  "authority_request",
  "authority_decision",
  "execution_trace",
  "evidence_packet",
  "settlement_packet",
] as const;

const pascal = (s: string) =>
  s.split("_").map((p) => p[0]!.toUpperCase() + p.slice(1)).join("");

async function render(): Promise<string> {
  const parts: string[] = [
    "/* eslint-disable */",
    "// GENERATED by scripts/generate-types.ts from ../../schemas. Do not edit.",
    "// Each profile is SemanticEnvelope & <Profile tightening>, mirroring the allOf in the schema.",
    "",
  ];
  const base = JSON.parse(readFileSync(join(schemas, "cep-semantic-envelope.schema.json"), "utf8"));
  base.title = "SemanticEnvelope";
  parts.push(
    await compile(base, "SemanticEnvelope", { bannerComment: "", additionalProperties: false, cwd: schemas }),
  );
  for (const profile of PROFILES) {
    const path = join(schemas, "profiles", "godspeed", `${profile}.v1.schema.json`);
    const full = JSON.parse(readFileSync(path, "utf8"));
    const tightening = full.allOf[1];
    tightening.title = `${pascal(profile)}Profile`;
    parts.push(
      await compile(tightening, `${pascal(profile)}Profile`, {
        bannerComment: "",
        additionalProperties: true,
      }),
    );
    parts.push(`export type ${pascal(profile)}Envelope = SemanticEnvelope & ${pascal(profile)}Profile;\n`);
  }
  const transition = JSON.parse(
    readFileSync(join(schemas, "profiles", "godspeed", "world-transition.v1.schema.json"), "utf8"),
  );
  transition.title = "WorldTransition";
  parts.push(
    await compile(transition, "WorldTransition", { bannerComment: "", additionalProperties: false }),
  );
  return parts.join("\n");
}

const text = await render();
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("stale generated types: run `bun run generate`");
    process.exit(1);
  }
  console.log("generated types are up to date");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
